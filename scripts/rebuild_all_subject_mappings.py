def run_rebuild():
    print("Loading kpi_data.js...")
    with open('kpi_data.js', 'r', encoding='utf-8') as f:
        text = f.read()

    prefix = '/* Generated for Thailand Open Curriculum Portal */\nconst OPEN_CURRICULUM_DATA = '
    if text.startswith(prefix):
        json_text = text[len(prefix):].rstrip().rstrip(';')
    else:
        idx = text.find('{')
        json_text = text[idx:].rstrip().rstrip(';')

    data = json.loads(json_text)

    # Apply additions
    applied = 0
    for k in data['kpis']:
        code = k['code']
        if code in SUBJECT_ADDITIONS:
            existing = k.get('courses', [])
            for c in SUBJECT_ADDITIONS[code]:
                if c not in existing:
                    existing.append(c)
            k['courses'] = existing
            applied += 1

    print(f"Applied mappings to {applied} KPI entries.")

    # Recalculate statistics per subject
    all_subjects = [
        'ภาษาไทย', 'คณิตศาสตร์', 'วิทยาศาสตร์และเทคโนโลยี', 
        'สังคมศึกษา ศาสนา และวัฒนธรรม', 'สุขศึกษาและพลศึกษา', 
        'ศิลปะ', 'การงานอาชีพ', 'ภาษาต่างประเทศ'
    ]

    total_secondary_kpis = 0
    total_secondary_mapped = 0
    total_primary_kpis = 0
    total_primary_mapped = 0

    print("\n=== AUDIT RESULTS AFTER FULL RESTORATION ===")
    for subj in all_subjects:
        kpis = [k for k in data['kpis'] if k['subject'] == subj]
        sec_kpis = [k for k in kpis if any(f'ม.{i}' in k['grade'] or 'ม.4-6' in k['grade'] for i in range(1, 7))]
        pri_kpis = [k for k in kpis if any(f'ป.{i}' in k['grade'] for i in range(1, 7))]

        sec_mapped = [k for k in sec_kpis if len(k.get('courses', [])) > 0]
        pri_mapped = [k for k in pri_kpis if len(k.get('courses', [])) > 0]

        total_secondary_kpis += len(sec_kpis)
        total_secondary_mapped += len(sec_mapped)
        total_primary_kpis += len(pri_kpis)
        total_primary_mapped += len(pri_mapped)

        # Update subject_counts
        data['subject_counts'][subj]['mapped'] = len(sec_mapped) + len(pri_mapped)
        data['subject_counts'][subj]['total'] = len(kpis)

        pct = (len(sec_mapped) / len(sec_kpis) * 100) if sec_kpis else 0
        print(f"{subj:30}: Secondary {len(sec_mapped):3d} / {len(sec_kpis):3d} ({pct:5.1f}%) | Primary Mapped: {len(pri_mapped)}/{len(pri_kpis)}")

    print("-" * 75)
    print(f"TOTAL SECONDARY: {total_secondary_mapped} / {total_secondary_kpis} ({total_secondary_mapped/total_secondary_kpis*100:.1f}%)")
    print(f"TOTAL PRIMARY:   {total_primary_mapped} / {total_primary_kpis} (0.0% - As expected: Secondary school)")
    print("-" * 75)

    data['total_stats']['total_mapped_kpis'] = total_secondary_mapped + total_primary_mapped

    # Save kpi_data.js
    with open('kpi_data.js', 'w', encoding='utf-8') as f:
        f.write('/* Generated for Thailand Open Curriculum Portal */\nconst OPEN_CURRICULUM_DATA = ')
        json.dump(data, f, ensure_ascii=False)
        f.write(';\n')
    print("kpi_data.js successfully written!")

    # 2. Update semester_catalog.json with new course mappings
    print("\nUpdating semester_catalog.json...")
    with open('semester_catalog.json', 'r', encoding='utf-8') as f:
        catalog = json.load(f)

    # Invert mapping: course_code -> list of KPI codes
    course_to_kpi_codes = {}
    for k in data['kpis']:
        for c_entry in k.get('courses', []):
            c_code = c_entry.split('_')[0]
            course_to_kpi_codes.setdefault(c_code, []).append(k['code'])

    updated_catalog_courses = 0
    by_code = catalog.get('by_course_code', {})
    for c_code, kpi_list in course_to_kpi_codes.items():
        if c_code in by_code:
            existing_kpis = by_code[c_code].get('kpi_codes', [])
            merged = sorted(list(dict.fromkeys(existing_kpis + kpi_list)))
            by_code[c_code]['kpi_codes'] = merged
            # update kpis_detail
            by_code[c_code]['kpis_detail'] = [
                {'code': kc, 'type': 'ตัวชี้วัด', 'weight': 1.0} for kc in merged
            ]
            updated_catalog_courses += 1
        else:
            # create basic course entry in catalog
            by_code[c_code] = {
                'code': c_code,
                'name': c_code,
                'grade': '',
                'term': '',
                'area': '',
                'credits': '1.0',
                'hours': '40',
                'description': '',
                'kpi_codes': sorted(list(dict.fromkeys(kpi_list))),
                'kpis_detail': [{'code': kc, 'type': 'ตัวชี้วัด', 'weight': 1.0} for kc in kpi_list],
                'file': ''
            }
            updated_catalog_courses += 1

    catalog['by_course_code'] = by_code
    with open('semester_catalog.json', 'w', encoding='utf-8') as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2)
    print(f"semester_catalog.json updated with {updated_catalog_courses} courses.")

if __name__ == '__main__':
    run_rebuild()
